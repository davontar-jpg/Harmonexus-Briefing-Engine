/** Compile a reviewer-verified official calendar. Never infer unpublished dates. */
import {readFile,writeFile} from 'node:fs/promises';
const file='config/official_high_impact_calendar.json', dest='src/28_OfficialCalendarCatalog.gs';
const catalog=JSON.parse(await readFile(file,'utf8'));
const date=s=>/^\d{4}-\d{2}-\d{2}$/.test(s) && Number.isFinite(Date.parse(s)) && new Date(s).toISOString().slice(0,10)===s;
if (catalog.schema!=='harmonexus.official-calendar.v1' || !date(catalog.verifiedOn) || !date(catalog.through) ||
  !Number.isInteger(catalog.reviewEveryDays) || catalog.reviewEveryDays<7 || catalog.reviewEveryDays>60) throw Error('Invalid calendar header.');
const seen=new Set(), events=[];
for (const [kind, group] of Object.entries(catalog.series)) {
  const source=catalog.sources[kind];
  if (!/^https:\/\/www\.(bls\.gov|federalreserve\.gov|bea\.gov)\//.test(source) || !/^(?:[01]\d|2[0-3]):[0-5]\d$/.test(group.time) ||
    !['scheduled','tentative'].includes(group.status)) throw Error('Unverified release metadata: '+kind);
  for (const day of group.dates) {
    const id=kind+'|'+day;
    if (!date(day)||day>catalog.through||seen.has(id)) throw Error('Invalid or duplicate release: '+id);
    seen.add(id); events.push({id,kind,day,time:group.time,label:group.label,channel:group.channel,status:group.status,source});
  }
}
if (new Set(catalog.nyseEarlyCloses).size!==catalog.nyseEarlyCloses.length || !catalog.nyseEarlyCloses.every(date)) throw Error('Invalid NYSE early close.');
const output='// Generated by tools/build-official-calendar.mjs from reviewed government schedules.\nconst HX_OFFICIAL_CALENDAR=Object.freeze('+
  JSON.stringify({...catalog,series:undefined,events:events.sort((a,b)=>(a.day+a.time).localeCompare(b.day+b.time))})+');\n';
if(process.argv.includes('--check')) {
  if ((await readFile(dest,'utf8')).replace(/\r\n/g,'\n')!==output) throw Error('Generated calendar does not match the reviewed catalog.');
} else await writeFile(dest,output,'utf8');
console.log('Verified catalog: '+events.length+' scheduled/tentative events through '+catalog.through);
